function move = createRuntimeMove(row,id,agvIndex,agv,now,empty,data,cfg)
%CREATERUNTIMEMOVE Immutable endpoints plus one next-event state per MoveID.
if nargin==0
 move=struct('MoveID',0,'ReadyActionID',"",'ActionType',"",'ParentCustomerTaskID',0,'CargoID',"", ...
  'SourceStation',NaN,'SourcePocketKey',"",'TargetStation',NaN,'TargetPocketKey',"", ...
  'AGVID',0,'AGVIndex',0,'FromStation',NaN,'DispatchTime',NaN,'SourceArrivalTime',NaN, ...
  'PickupStartTime',NaN,'PickupTime',NaN,'TargetArrivalTime',NaN,'DropoffStartTime',NaN, ...
  'DropoffTime',NaN,'CompletionTime',NaN,'Phase',"",'NextEventTime',Inf,'WaitSince',Inf, ...
  'SourceAccess',[],'TargetAccess',[],'SourceReleased',false,'EmptyDistance',0,'LoadedDistance',0,'ActionPayload',struct(), ...
  'EntranceStation',NaN,'HomeStation',NaN,'ExitDistance',0,'ExitArrivalTime',NaN, ...
  'ReturnHomeDistance',0,'ReturnHomeStartTime',NaN,'HomeArrivalTime',NaN,'VehicleFinishTime',NaN); return;
end
a=row.ActionPayload{1};
source=unique([a.SourceStation;getSlotAccessStations(a.SourceStation,data)]);
target=unique([a.TargetStation;getSlotAccessStations(a.TargetStation,data)]);
move=struct('MoveID',id,'ReadyActionID',row.ReadyActionID,'ActionType',a.ActionType, ...
 'ParentCustomerTaskID',a.ParentCustomerTaskID,'CargoID',a.CargoID,'SourceStation',a.SourceStation, ...
 'SourcePocketKey',a.SourcePocketKey,'TargetStation',a.TargetStation,'TargetPocketKey',a.TargetPocketKey, ...
 'AGVID',agv.ID,'AGVIndex',agvIndex,'FromStation',agv.CurrentStation,'DispatchTime',now, ...
 'SourceArrivalTime',NaN,'PickupStartTime',NaN,'PickupTime',NaN,'TargetArrivalTime',NaN, ...
 'DropoffStartTime',NaN,'DropoffTime',NaN,'CompletionTime',NaN, ...
 'Phase',"ToSource",'NextEventTime',now+getTravelTime(empty,cfg),'WaitSince',Inf, ...
 'SourceAccess',source,'TargetAccess',target,'SourceReleased',false,'EmptyDistance',empty,'LoadedDistance',a.LoadedDistance, ...
 'ActionPayload',a, ...
 'EntranceStation',NaN,'HomeStation',cfg.agvInitialStations(agvIndex),'ExitDistance',0,'ExitArrivalTime',NaN, ...
 'ReturnHomeDistance',0,'ReturnHomeStartTime',NaN,'HomeArrivalTime',NaN,'VehicleFinishTime',NaN);
entrances=unique(data.lanes.StationMark(data.lanes.PocketKey==a.TargetPocketKey & data.lanes.StationType=="Entrance"));
assert(numel(entrances)==1,'AGV:LaneEntrance','Target PocketKey %s must have exactly one Entrance.',char(a.TargetPocketKey));
move.EntranceStation=entrances;
move.ExitDistance=getTravelDistance(a.TargetStation,move.EntranceStation,data);
assert(isfinite(move.ExitDistance) && move.ExitDistance>=0,'AGV:ExitRoute','Target-to-Entrance route is unreachable.');
end
