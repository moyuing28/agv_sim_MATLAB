function rows = runtimeMoveTable(moves)
%RUNTIMEMOVETABLE Flat export; heterogeneous payloads remain in result.moves.
rows=table(zeros(0,1),strings(0,1),strings(0,1),strings(0,1),zeros(0,1),strings(0,1), ...
 zeros(0,1),zeros(0,1),zeros(0,1),zeros(0,1),zeros(0,1),zeros(0,1),zeros(0,1),zeros(0,1), ...
 zeros(0,1),zeros(0,1),'VariableNames',{'MoveID','ReadyActionID','ActionType','RelocationKind', ...
 'ParentTaskID','CargoID','AGVID','SourceStation','TargetStation','DispatchTime','PickupTime', ...
 'DropoffTime','CompletionTime','EmptyDistance','LoadedDistance','RequiredFillingCountBefore'});
for m=moves
 kind=""; count=NaN;
 if isfield(m.ActionPayload,'RelocationKind'), kind=m.ActionPayload.RelocationKind; end
 if isfield(m.ActionPayload,'RequiredFillingCountBefore'), count=m.ActionPayload.RequiredFillingCountBefore; end
 rows(end+1,:)={m.MoveID,m.ReadyActionID,m.ActionType,kind,m.ParentCustomerTaskID,m.CargoID,m.AGVID, ...
  m.SourceStation,m.TargetStation,m.DispatchTime,m.PickupTime,m.DropoffTime,m.CompletionTime, ...
  m.EmptyDistance,m.LoadedDistance,count}; %#ok<AGROW>
end
end
